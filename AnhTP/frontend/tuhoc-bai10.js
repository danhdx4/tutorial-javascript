let a = 99;
let b = 10;
let c = 77;
let d = 88;

a++; // Toán tử tăng (increment)
b--;
++c;
--d;

console.log("Giá trị của a sau khi tăng: " + a); // Kết quả: 100
console.log("Giá trị của b sau khi giảm: " + b); // Kết quả: 9
console.log("Giá trị của c sau khi tăng: " + c); // Kết quả: 78
console.log("Giá trị của d sau khi giảm: " + d); // Kết quả: 87
